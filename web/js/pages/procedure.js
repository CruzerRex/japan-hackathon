import { api } from '../api.js';
import { html, raw, mount, $, $$, actions, ic, avatar, relTime, fmtDate, statusBadge, evidenceBadge, EVIDENCE_LEGEND, empty,
  modal, confirmDialog, toast, toastError, loading, tsToSec, esc, meter } from '../ui.js';
import { nm } from '../i18n.js';
import { pageHead } from './_common.js';
import { openAssistant } from '../app.js';

const FLOW = ['DRAFT', 'AI_PROCESSED', 'EXPERT_REVIEW', 'APPROVED', 'PUBLISHED'];
const ACTION_LABEL = { submit: ['Submit for expert review', 'btn-primary', 'shield'], approve: ['Approve', 'btn-ok', 'check'],
  reject: ['Reject', 'btn-danger', 'x'], request_revision: ['Request revision', 'btn-ghost', 'edit'], publish: ['Publish as training', 'btn-primary', 'academy'] };

export async function render(el, ctx) {
  let tab = ctx.query.tab || 'procedure';
  let data; let content; let dirty = false;
  const load = async (versionId) => {
    data = await api.get(`/api/procedures/${ctx.params.id}${versionId ? `?version=${versionId}` : ''}`);
    content = structuredClone(data.version.content);
  };
  mount(el, loading(5));
  await load(ctx.query.version);

  const v = () => data.version;
  const staff = ctx.can('procedure.read_unpublished');

  const statusline = () => {
    const s = v().status;
    if (['REJECTED', 'NEEDS_REVISION', 'SUPERSEDED'].includes(s)) {
      return html`<div class="statusline"><span class="sl-node bad">${s.replace('_', ' ')}</span></div>`;
    }
    const idx = FLOW.indexOf(s);
    return html`<div class="statusline">${FLOW.map((f, i) => html`${i ? html`<span class="sl-bar"></span>` : ''}<span class="sl-node ${i < idx ? 'done' : i === idx ? 'cur' : ''}">${i < idx ? ic('check', 11) : ''}${f.replace('_', ' ').toLowerCase()}</span>`)}</div>`;
  };

  const banner = () => {
    const s = v().status;
    if (s === 'PUBLISHED') return html`<div class="notice ok">${ic('shield', 16)}<div>Expert-approved training material. Approved by <b>${v().approved_by_name || '—'}</b> on ${fmtDate(v().approved_at)}${v().published_by_name ? `, published by ${v().published_by_name}` : ''}.
      Values must still be checked against the current drawing/specification.</div></div>`;
    if (s === 'SUPERSEDED') return html`<div class="notice">${ic('clock', 16)}<div>This is a previous approved version kept for traceability. ${data.procedure.published_version_id ? html`<a href="#/procedures/${data.procedure.id}">Open the current published version</a>.` : ''}</div></div>`;
    if (s === 'REJECTED') return html`<div class="notice danger">${ic('x', 16)}<div>Rejected by an expert. It will never be shown as training material.</div></div>`;
    return html`<div class="notice warn">${ic('flag', 16)}<div><b>Not approved training material.</b> ${s === 'AI_PROCESSED' ? 'Generated by the extraction pipeline — an expert must review every step before it can be approved.' : s === 'EXPERT_REVIEW' ? 'Under expert review.' : s === 'APPROVED' ? 'Approved — publish to make it available in the Training Academy.' : 'Draft.'}</div></div>`;
  };

  const tabs = () => {
    const t = [['procedure', 'Procedure'], ['source', 'Source & evidence']];
    if (staff) t.push(['assessment', `Assessment (${content.questions.length + content.scenarios.length})`]);
    t.push(['history', `History (${data.versions.length})`], ['translations', 'Translations']);
    if (staff) t.push(['insights', 'Learning insights']);
    return html`<div class="tabs" role="tablist">${t.map(([k, l]) => html`<button class="tab ${tab === k ? 'on' : ''}" data-action="tab" data-k="${k}" role="tab">${l}</button>`)}</div>`;
  };

  const draw = async () => {
    const p = data.procedure;
    mount(el, html`
      ${pageHead({ crumb: { href: '#/library', label: 'Knowledge Library' }, eyebrow: `${p.code} · version ${v().version_no}`, icon: 'library',
        title: content.title,
        sub: html`${data.owner ? html`Source expert <b>${nm(data.owner.name, data.owner.name_ja)}</b> (${data.owner.years_experience} yrs) · ` : ''}${content.machine || ''}
          ${data.skills.map((s) => html` <span class="skill-tag">${s.code} · ${nm(s.name, s.name_ja)}</span>`)}`,
        actions: html`
          ${data.versions.length > 1 ? html`<select id="ver-sel" aria-label="Version" style="width:auto">${data.versions.map((x) => html`<option value="${x.id}" ${x.id === v().id ? 'selected' : ''}>v${x.version_no} · ${x.status.toLowerCase().replace('_', ' ')}</option>`)}</select>` : ''}
          ${data.actions.map((a) => { const [l, c, i] = ACTION_LABEL[a.action]; return html`<button class="btn ${c}" data-action="transition" data-a="${a.action}" data-c="${a.needs_comment ? 1 : 0}">${ic(i, 15)} ${l}</button>`; })}
          ${data.can_revise ? html`<button class="btn btn-ghost" data-action="revise">${ic('edit', 15)} New revision</button>` : ''}
          <div class="pop-wrap"><button class="btn btn-ghost" data-action="export-menu">${ic('download', 15)} Export</button>
            <div class="pop pop-right" id="exp-pop" hidden style="width:240px">
              <a class="pop-item" href="/api/procedures/${p.id}/export?format=md&version=${v().id}&download=1">${ic('file', 16)}<span><b>Markdown SOP</b><small>Readable, printable</small></span></a>
              <a class="pop-item" href="/api/procedures/${p.id}/export?format=json&version=${v().id}&download=1">${ic('layers', 16)}<span><b>Structured JSON</b><small>Portable, with evidence</small></span></a></div></div>` })}
      ${statusline()}
      ${banner()}
      <div style="height:14px"></div>
      ${tabs()}
      <div id="tab-body"></div>`);
    await drawTab();
    $('#ver-sel', el)?.addEventListener('change', async (e) => { await load(e.target.value); draw(); });
  };

  // -- tab: procedure --------------------------------------------------------------------------------------------
  const reviewMode = () => data.can_confirm || data.editable;
  const stepView = (s, n) => {
    const tips = content.tips.filter((x) => x.step_id === s.step_id);
    const mis = content.mistakes.filter((x) => x.step_id === s.step_id);
    const fms = content.failure_modes.filter((x) => x.step_id === s.step_id);
    const needs = (s.source_type === 'inference' || !s.evidence_verified || s.safety_critical) && s.source_type !== 'expert_edit';
    return html`<div class="step ${s.safety_critical ? 'safety' : ''} ${ctx.query.step === s.step_id ? 'highlight' : ''}" id="st-${s.step_id}">
      <div class="step-n">${n}</div>
      <div>
        <h3>${s.title}
          ${s.safety_critical ? html`<span class="badge b-danger">${ic('shield', 11)} Safety-critical</span>` : ''}
          ${s.critical_checkpoint ? html`<span class="badge b-warn">Critical checkpoint</span>` : ''}
          ${s.expert_edited ? html`<span class="badge b-ok" title="Edited by ${s.edited_by}">Edited by ${s.edited_by}</span>` : ''}</h3>
        <p class="instr">${s.instruction}</p>
        ${s.why ? html`<p class="why"><b>Why</b>${s.why}</p>` : ''}
        ${s.quality_check ? html`<p class="why"><b>Check</b>${s.quality_check}</p>` : ''}
        ${s.tolerance ? html`<p class="why"><b>Stated requirement</b>${s.tolerance.text} <small class="muted">(verify against drawing/spec)</small></p>` : ''}
        ${s.evidence_quote ? html`<div class="quote">“${s.evidence_quote}” ${s.source_timestamp ? html`<a href="#" class="mono" data-action="goto-source" data-ts="${s.source_timestamp}">▶ ${s.source_timestamp}</a>` : ''}</div>` : ''}
        <div class="step-meta">
          ${evidenceBadge(s.source_type, s.evidence_verified, s.source_timestamp)}
          ${staff ? html`<span class="badge b-neutral" title="Extractor confidence (rule-based or model)">conf. ${Math.round(s.confidence * 100)}%</span>` : ''}
          ${s.expert_confirmed ? html`<span class="badge b-ok">${ic('check', 11)} Confirmed by ${s.confirmed_by}</span>`
            : reviewMode() && s.source_type !== 'expert_edit' ? (needs ? html`<span class="badge b-warn">Needs individual review</span>` : html`<span class="badge b-neutral">Unconfirmed</span>`) : ''}
          ${data.can_confirm ? html`<button class="btn btn-sm ${s.expert_confirmed ? 'btn-ghost' : 'btn-ok'}" data-action="confirm" data-id="${s.step_id}" data-v="${s.expert_confirmed ? 0 : 1}">${s.expert_confirmed ? 'Undo confirm' : html`${ic('check', 13)} Confirm step`}</button>` : ''}
          ${data.editable ? html`<button class="btn btn-sm btn-ghost" data-action="edit-step" data-id="${s.step_id}">${ic('edit', 13)} Edit</button>
            <button class="icon-btn" data-action="move" data-id="${s.step_id}" data-d="-1" aria-label="Move up">↑</button>
            <button class="icon-btn" data-action="move" data-id="${s.step_id}" data-d="1" aria-label="Move down">↓</button>
            <button class="icon-btn" data-action="del-step" data-id="${s.step_id}" aria-label="Delete step">${ic('x', 14)}</button>` : ''}
          ${!staff ? html`<button class="btn btn-sm btn-ghost" data-action="flag" data-id="${s.step_id}">${ic('flag', 13)} Unclear?</button>` : ''}
        </div>
        ${tips.length || mis.length || fms.length ? html`<div class="attach">
          ${tips.map((x) => html`<div class="attach-item tip"><span class="lbl">Tip</span><div>${x.text} ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}
          ${mis.map((x) => html`<div class="attach-item mistake"><span class="lbl">Mistake</span><div>${x.text}${x.consequence ? html` <small class="muted">→ ${x.consequence}</small>` : ''} ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}
          ${fms.map((x) => html`<div class="attach-item fm"><span class="lbl">If</span><div>${x.symptom} → <b>${x.action}</b> ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}
        </div>` : ''}
      </div></div>`;
  };

  const procedureTab = () => {
    const oqs = content.open_questions.filter((q) => !q.resolved);
    const gTips = content.tips.filter((x) => !x.step_id); const gMis = content.mistakes.filter((x) => !x.step_id);
    const gFm = content.failure_modes.filter((x) => !x.step_id);
    const ev = data.evidence;
    return html`
      ${reviewMode() ? html`<div class="card accent" style="margin-bottom:16px">
        <div class="card-h"><h2>${ic('shield', 18)} Expert review checklist<span class="sub">Approval is blocked until every item below is resolved — AI output never self-approves.</span></h2></div>
        <div class="ev-summary" style="margin-bottom:12px">
          <div><small class="muted">Steps</small><b>${ev.total}</b></div>
          <div><small class="muted">Evidence-verified</small><b>${ev.verified}</b></div>
          <div><small class="muted">Demonstrated</small><b>${ev.by_source.demonstration}</b></div>
          <div><small class="muted">Unconfirmed steps</small><b style="color:${ev.needs_confirmation ? 'var(--warn)' : 'var(--ok)'}">${ev.needs_confirmation}</b></div>
          <div><small class="muted">Open questions</small><b style="color:${ev.open_questions ? 'var(--warn)' : 'var(--ok)'}">${ev.open_questions}</b></div></div>
        ${data.approval_blockers.length ? html`<details ${data.approval_blockers.length <= 6 ? 'open' : ''}><summary class="small" style="cursor:pointer;color:var(--warn)">${data.approval_blockers.length} item(s) block approval</summary>
            <ul class="blockers">${data.approval_blockers.map((b) => html`<li>${b}</li>`)}</ul></details>`
          : html`<div class="notice ok">${ic('check', 16)} All checks pass — ${v().status === 'EXPERT_REVIEW' ? 'ready for approval' : 'submit for expert review, then approve'}.</div>`}
        ${data.validation.errors.length ? html`<div class="notice danger" style="margin-top:8px">${ic('risk', 16)}<div>${data.validation.errors.map((e) => html`<div>${e.path}: ${e.message}</div>`)}</div></div>` : ''}
        <div class="row" style="margin-top:10px">${data.can_confirm ? html`<button class="btn btn-sm btn-ghost" data-action="confirm-verified">${ic('check', 13)} Confirm all steps with verified evidence</button>` : ''}
          ${data.editable ? html`<button class="btn btn-sm btn-ghost" data-action="add-step">${ic('plus', 13)} Add step</button>` : ''}</div>
      </div>` : ''}
      ${oqs.length && reviewMode() ? html`<div class="card" style="margin-bottom:16px;border-color:rgba(178,157,255,.45)">
        <div class="card-h"><h2>Tacit knowledge questions for the expert<span class="sub">The extractor found vague or missing knowledge. The expert's answer becomes an expert-authored tip on the step.</span></h2></div>
        ${oqs.map((q) => html`<div class="q-card" style="margin-bottom:8px"><div class="q-prompt">${q.text}</div><small class="muted">${q.reason}${q.step_id ? ` · ${q.step_id}` : ''}</small>
          ${data.can_confirm ? html`<div class="row" style="margin-top:8px"><input id="oq-${q.id}" placeholder="Expert's answer, e.g. 'Rock about 5° either side until the needle reverses'" style="flex:1">
            <button class="btn btn-sm btn-primary" data-action="resolve-oq" data-id="${q.id}">Answer</button>
            <button class="btn btn-sm btn-ghost" data-action="dismiss-oq" data-id="${q.id}">Not applicable</button></div>` : ''}</div>`)}
      </div>` : ''}
      <div class="grid g-side">
        <div class="stack">
          <div class="card"><div class="card-h"><h2>Steps</h2><div class="ev-legend">${Object.entries(EVIDENCE_LEGEND).map(([k]) => evidenceBadge(k, true))}</div></div>
            <div class="steps">${content.steps.map((s, i) => stepView(s, i + 1))}</div></div>
          ${gTips.length || gMis.length || gFm.length ? html`<div class="card"><div class="card-h"><h2>General expert knowledge<span class="sub">Not tied to a single step</span></h2></div>
            <div class="attach">${gTips.map((x) => html`<div class="attach-item tip"><span class="lbl">Tip</span><div>${x.text} ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}
              ${gMis.map((x) => html`<div class="attach-item mistake"><span class="lbl">Mistake</span><div>${x.text} ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}
              ${gFm.map((x) => html`<div class="attach-item fm"><span class="lbl">If</span><div>${x.symptom} → <b>${x.action}</b> ${evidenceBadge(x.source_type, x.evidence_verified, x.source_timestamp)}</div></div>`)}</div></div>` : ''}
        </div>
        <div class="stack">
          <div class="card"><h3 style="margin-bottom:8px">Purpose</h3><p class="dim">${content.purpose || html`<span class="muted">Not stated</span>`}</p>
            ${content.scope ? html`<p class="small muted">${content.scope}</p>` : ''}</div>
          ${content.safety.length ? html`<div class="card" style="border-color:rgba(240,98,95,.4)"><div class="card-h"><h3>${ic('shield', 16)} Safety</h3></div>
            ${content.safety.map((s) => html`<div class="attach-item mistake" style="margin-bottom:6px"><div>${s.text}<div class="step-meta">${evidenceBadge(s.source_type, s.evidence_verified, s.source_timestamp)}
              ${s.expert_confirmed ? html`<span class="badge b-ok">Confirmed</span>` : data.can_confirm ? html`<button class="btn btn-sm btn-ok" data-action="confirm" data-id="${s.id}" data-v="1">Confirm</button>` : html`<span class="badge b-warn">Unconfirmed</span>`}</div></div></div>`)}
            <p class="small muted">Kizuna Forge does not certify safety. Follow your plant's approved safety procedures.</p></div>` : ''}
          ${content.prerequisites.length ? html`<div class="card"><h3 style="margin-bottom:8px">Prerequisites</h3><ul class="small dim" style="padding-left:18px;margin:0">${content.prerequisites.map((x) => html`<li>${x}</li>`)}</ul></div>` : ''}
          ${content.equipment.length ? html`<div class="card"><h3 style="margin-bottom:8px">Equipment</h3><div class="skill-tags">${content.equipment.map((e) => html`<span class="skill-tag">${e.name}</span>`)}</div></div>` : ''}
          ${v().extraction_meta && v().extraction_meta.provider ? html`<div class="card flat"><h3 style="margin-bottom:6px">Extraction record</h3>
            <dl class="kv small"><dt>Provider</dt><dd>${v().extraction_meta.provider_label}</dd><dt>Video analysed</dt><dd>${v().extraction_meta.video_analyzed ? 'yes' : 'no — markers are expert annotations'}</dd>
              <dt>Injection screen</dt><dd>${v().extraction_meta.injection_findings?.length ? `${v().extraction_meta.injection_findings.length} finding(s) ignored` : 'clean'}</dd>
              <dt>Duration</dt><dd>${v().extraction_meta.duration_ms} ms</dd></dl></div>` : ''}
          <div class="card flat"><h3 style="margin-bottom:6px">Ask about this procedure</h3>
            <p class="small muted">The assistant answers from approved versions only.</p>
            <button class="btn btn-sm btn-ghost" data-action="ask">${ic('chat', 14)} Open assistant</button></div>
        </div>
      </div>`;
  };

  // -- tab: source ----------------------------------------------------------------------------------------------------
  const sourceTab = () => {
    const c = data.capture;
    if (!c) return html`<div class="card">${empty('Source not available', staff ? 'This procedure was authored manually or the capture is not linked.' : 'Raw expert recordings are visible to experts and trainers. Evidence quotes are shown on each step.')}</div>`;
    const lines = (c.transcript || '').split('\n');
    return html`<div class="grid g2">
      <div class="card"><div class="card-h"><h2>Transcript<span class="sub">Click a timestamp on any step to jump here</span></h2></div>
        <div class="transcript" id="tx">${lines.map((l) => { const m = l.match(/(\d{1,2}:\d{2}:\d{2})/); return html`<div data-ts="${m ? m[1] : ''}">${l}</div>`; })}</div></div>
      <div class="stack">
        ${c.video ? html`<div class="card"><h3 style="margin-bottom:8px">Demonstration video</h3><video id="pvid" controls preload="metadata" src="/api/files/${c.video.id}"></video></div>`
          : html`<div class="card flat"><p class="muted small">${ic('play', 14)} No video attached to this capture; evidence links point to transcript timestamps and demonstration markers.</p></div>`}
        <div class="card"><h3 style="margin-bottom:8px">Demonstration markers</h3>
          ${c.markers.length ? c.markers.map((m) => html`<div class="row small" style="padding:4px 0"><a href="#" class="mono" data-action="goto-source" data-ts="${new Date(m.t_seconds * 1000).toISOString().substr(11, 8)}">▶ ${new Date(m.t_seconds * 1000).toISOString().substr(11, 8)}</a><span class="badge b-neutral">${m.kind}</span>${m.label}</div>`) : html`<p class="muted small">None.</p>`}</div>
        <div class="card flat"><h3 style="margin-bottom:6px">Consent</h3><p class="small dim">${c.consent_given ? c.consent_scope : 'Not recorded'}</p></div>
      </div></div>`;
  };

  // -- tab: assessment -----------------------------------------------------------------------------------------------
  const assessmentTab = () => html`
    <div class="notice" style="margin-bottom:12px">${ic('academy', 16)}<div>Items marked <b>critical</b> are gated separately from accuracy: missing one is a critical failure regardless of score. Generated items need expert review like any other content.</div></div>
    ${data.editable ? html`<div class="row" style="margin-bottom:12px"><button class="btn btn-sm btn-ghost" data-action="edit-q" data-id="">${ic('plus', 13)} Add question</button></div>` : ''}
    ${content.questions.map((q, i) => html`<div class="q-card ${q.critical ? 'critical' : ''}"><div class="q-head">Q${i + 1} ${q.critical ? html`<span class="badge b-warn">critical</span>` : ''}
        <span class="badge b-neutral">${q.origin}</span>${q.step_id ? html`<span class="mono">${q.step_id}</span>` : ''}
        ${data.editable ? html`<span style="margin-left:auto"><button class="btn btn-sm btn-ghost" data-action="edit-q" data-id="${q.id}">Edit</button> <button class="btn btn-sm btn-danger" data-action="del-q" data-id="${q.id}">Delete</button></span>` : ''}</div>
      <div class="q-prompt">${q.prompt}</div>${q.options.map((o, j) => html`<div class="option ${j === q.answer_index ? 'right' : ''}" style="cursor:default"><span class="ol">${'ABCDEF'[j]}</span>${o}</div>`)}
      ${q.explanation ? html`<p class="small muted">${q.explanation}</p>` : ''}</div>`)}
    ${content.scenarios.map((s, i) => html`<div class="q-card ${s.critical ? 'critical' : ''}"><div class="q-head">Scenario ${i + 1} ${s.critical ? html`<span class="badge b-warn">critical</span>` : ''}<span class="badge b-neutral">${s.origin}</span>
        ${data.editable ? html`<span style="margin-left:auto"><button class="btn btn-sm btn-danger" data-action="del-sc" data-id="${s.id}">Delete</button></span>` : ''}</div>
      <div class="q-prompt">${s.situation}</div>${s.options.map((o, j) => html`<div class="option ${o.correct ? 'right' : ''}" style="cursor:default"><span class="ol">${'ABCDE'[j]}</span><span>${o.text}<br><small class="muted">${o.feedback}</small></span></div>`)}</div>`)}
    ${!content.questions.length && !content.scenarios.length ? html`<div class="card">${empty('No assessment items', 'Add at least one question before publishing.')}</div>` : ''}`;

  // -- tab: history ----------------------------------------------------------------------------------------------------
  const historyTab = () => html`<div class="grid g2">
    <div class="card"><div class="card-h"><h2>Versions</h2></div>
      <div class="table-wrap"><table><tbody>${data.versions.map((x) => html`<tr><td><b>v${x.version_no}</b> ${statusBadge(x.status)}${x.id === data.procedure.published_version_id ? html` <span class="badge b-amber">current</span>` : ''}
        <span class="sub">${x.change_summary || ''}</span><span class="sub">by ${x.created_by_name || '—'} · ${fmtDate(x.created_at)}${x.approved_by_name ? ` · approved by ${x.approved_by_name}` : ''}</span></td>
        <td><a href="#" data-action="view-ver" data-id="${x.id}">View</a></td></tr>`)}</tbody></table></div>
      ${data.versions.length > 1 ? html`<div class="sep"></div><h3 style="margin-bottom:8px">Compare versions</h3><div class="row">
        <select id="da">${data.versions.map((x, i) => html`<option value="${x.id}" ${i === 1 ? 'selected' : ''}>v${x.version_no}</option>`)}</select> →
        <select id="db">${data.versions.map((x, i) => html`<option value="${x.id}" ${i === 0 ? 'selected' : ''}>v${x.version_no}</option>`)}</select>
        <button class="btn btn-sm btn-ghost" data-action="diff">Compare</button></div><div id="diff-out" style="margin-top:12px"></div>` : ''}</div>
    <div class="card"><div class="card-h"><h2>Review trail</h2></div>
      ${data.events.length ? html`<ul class="tl">${data.events.map((e) => html`<li class="${e.to_status === 'PUBLISHED' || e.to_status === 'APPROVED' ? 'ok' : e.to_status === 'REJECTED' || e.to_status === 'NEEDS_REVISION' ? 'bad' : 'warn'}">
        <b>${e.from_status ? `${e.from_status} → ` : ''}${e.to_status}</b><div class="small muted">${e.actor_name || '—'} (${e.actor_role || ''}) · ${fmtDate(e.created_at, true)}</div>
        ${e.comment ? html`<div class="small dim">“${e.comment}”</div>` : ''}</li>`)}</ul>` : html`<p class="muted small">Visible to experts and trainers.</p>`}</div></div>`;

  // -- tab: translations ------------------------------------------------------------------------------------------------
  const translationsTab = async () => {
    const tr = await api.get(`/api/versions/${v().id}/translations/ja`);
    const t = tr.translation; const tc = t?.content || { steps: {}, safety: {} };
    const canEdit = ctx.can('translation.edit');
    return html`
      <div class="notice info" style="margin-bottom:12px">${ic('globe', 16)}<div>Translations are linked to <b>v${tr.version.version_no}</b> of the source and never replace it.
        ${tr.safety_review_required ? html`This procedure contains safety-critical content, so the Japanese text must be reviewed by a qualified second person.` : ''}</div></div>
      <div class="row between" style="margin-bottom:12px"><div>Japanese (日本語) ${t ? html`<span class="badge ${t.status === 'reviewed' ? 'b-ok' : 'b-warn'}">${t.status.replace(/_/g, ' ')}</span>
        <small class="muted"> · by ${t.created_by_name || '—'}${t.reviewed_by_name ? ` · reviewed by ${t.reviewed_by_name}` : ''}</small>` : html`<span class="badge b-neutral">not translated</span>`}</div>
        <div class="row">${canEdit ? html`<button class="btn btn-sm btn-primary" data-action="save-tr">Save translation</button>` : ''}
          ${t && t.status !== 'reviewed' && ctx.can('translation.review') ? html`<button class="btn btn-sm btn-ok" data-action="review-tr">${ic('check', 13)} Approve translation</button>` : ''}</div></div>
      <div class="card" style="padding:0"><div class="table-wrap"><table>
        <thead><tr><th style="width:46%">Source (English)</th><th>日本語</th></tr></thead><tbody>
        <tr><td><b>${tr.source.title}</b></td><td><input data-tr="title" value="${tc.title || ''}" ${canEdit ? '' : 'disabled'}></td></tr>
        <tr><td class="dim">${tr.source.purpose}</td><td><textarea data-tr="purpose" rows="2" ${canEdit ? '' : 'disabled'}>${tc.purpose || ''}</textarea></td></tr>
        ${tr.source.steps.map((s, i) => html`<tr><td><b>${i + 1}. ${s.title}</b> ${s.safety_critical ? html`<span class="badge b-danger">safety</span>` : ''}<p class="small dim">${s.instruction}</p></td>
          <td><input data-tr-step="${s.step_id}" data-k="title" value="${tc.steps?.[s.step_id]?.title || ''}" placeholder="手順名" ${canEdit ? '' : 'disabled'}>
            <textarea data-tr-step="${s.step_id}" data-k="instruction" rows="2" style="margin-top:6px" placeholder="指示" ${canEdit ? '' : 'disabled'}>${tc.steps?.[s.step_id]?.instruction || ''}</textarea></td></tr>`)}
        ${tr.source.safety.map((s) => html`<tr><td><span class="badge b-danger">safety</span> ${s.text}</td><td><textarea data-tr-safety="${s.id}" rows="2" ${canEdit ? '' : 'disabled'}>${tc.safety?.[s.id] || ''}</textarea></td></tr>`)}
        </tbody></table></div></div>`;
  };

  // -- tab: insights ------------------------------------------------------------------------------------------------------
  const insightsTab = async () => {
    const ins = await api.get(`/api/procedures/${data.procedure.id}/insights`);
    const titles = Object.fromEntries(content.steps.map((s) => [s.step_id, s.title]));
    return html`<div class="grid g2">
      <div class="card"><div class="card-h"><h2>Where learners struggle<span class="sub">${ins.attempts} submitted assessments · ${ins.rule}</span></h2></div>
        ${ins.steps.length ? ins.steps.map((s) => html`<div style="margin-bottom:10px"><div class="row between small"><span>${titles[s.step_id] || s.step_id} ${s.flagged ? html`<span class="badge b-danger">documentation gap?</span>` : ''}</span>
          <span class="mono">${Math.round(s.error_rate * 100)}% wrong (${s.wrong}/${s.answers})</span></div>${meter(s.error_rate * 100, 100, s.flagged ? 'danger' : '')}
          ${s.flagged && ctx.can('procedure.read_unpublished') ? html`<button class="btn btn-sm btn-ghost" style="margin-top:6px" data-action="gap" data-id="${s.step_id}">${ic('flag', 13)} Log improvement item for the expert</button>` : ''}</div>`)
          : empty('No assessment data yet', 'Once trainees take the assessment, error rates per step appear here.')}</div>
      <div class="card"><div class="card-h"><h2>Improvement items<span class="sub">From learners, trainers and assessment analytics — inputs for the next revision</span></h2></div>
        ${data.feedback.length ? data.feedback.map((f) => html`<div class="req" style="margin-bottom:8px"><div class="row between"><span class="badge ${f.status === 'open' ? 'b-warn' : 'b-ok'}">${f.status}</span>
          <small class="muted">${f.source} · ${f.created_by_name || ''} · ${relTime(f.created_at)}</small></div><div>${f.note}</div>${f.step_id ? html`<small class="mono muted">${f.step_id} · ${titles[f.step_id] || ''}</small>` : ''}
          ${f.status === 'open' && ctx.can('feedback.resolve') ? html`<div class="row"><button class="btn btn-sm btn-ghost" data-action="fb" data-id="${f.id}" data-s="addressed">Mark addressed</button>
            <button class="btn btn-sm btn-ghost" data-action="fb" data-id="${f.id}" data-s="dismissed">Dismiss</button></div>` : ''}</div>`)
          : empty('No improvement items', 'Learners can flag unclear steps from the training module.')}</div></div>`;
  };

  const drawTab = async () => {
    const body = $('#tab-body', el);
    const fn = { procedure: procedureTab, source: sourceTab, assessment: assessmentTab, history: historyTab, translations: translationsTab, insights: insightsTab }[tab] || procedureTab;
    mount(body, loading(2));
    try { mount(body, await fn()); } catch (e) { mount(body, html`<div class="card error-card"><p>${e.message}</p></div>`); }
    if (tab === 'procedure' && ctx.query.step) $(`#st-${ctx.query.step}`, el)?.scrollIntoView({ block: 'center' });
  };

  // -- persistence helpers ------------------------------------------------------------------------------------------------
  const saveContent = async (note) => {
    const r = await api.put(`/api/versions/${v().id}/content`, { content, note });
    if (r.validation.errors.length) toast(`Saved with ${r.validation.errors.length} validation error(s)`, 'error'); else toast('Saved');
    await load(v().id); draw();
  };
  const stepModal = async (step) => {
    const isNew = !step;
    step = step || { title: '', instruction: '', why: '', quality_check: '', safety_critical: false, critical_checkpoint: false };
    return modal({
      title: isNew ? 'Add step' : `Edit step — ${step.title}`, wide: true,
      body: html`${!isNew && step.evidence_quote ? html`<div class="quote" style="margin-bottom:12px">Source evidence: “${step.evidence_quote}” ${step.source_timestamp || ''}</div>` : ''}
        <label class="field"><span>Title</span><input id="e-title" value="${step.title}"></label>
        <label class="field"><span>Instruction</span><textarea id="e-instr" rows="3">${step.instruction}</textarea></label>
        <label class="field"><span>Why it matters</span><textarea id="e-why" rows="2">${step.why}</textarea></label>
        <label class="field"><span>Quality check / pass criterion</span><textarea id="e-qc" rows="2">${step.quality_check}</textarea></label>
        <div class="row"><label class="check"><input type="checkbox" id="e-safety" ${step.safety_critical ? 'checked' : ''}> Safety-critical</label>
          <label class="check"><input type="checkbox" id="e-crit" ${step.critical_checkpoint ? 'checked' : ''}> Critical checkpoint</label></div>
        <p class="small muted">Edits are recorded as expert-authored changes; the original evidence quote stays attached.</p>`,
      actions: [{ label: 'Cancel' }, { label: 'Save step', onClick: (w) => ({ title: $('#e-title', w).value, instruction: $('#e-instr', w).value, why: $('#e-why', w).value,
        quality_check: $('#e-qc', w).value, safety_critical: $('#e-safety', w).checked, critical_checkpoint: $('#e-crit', w).checked }) }],
    });
  };

  await draw();
  const off = actions(el, {
    tab: async (b) => { tab = b.dataset.k; $$('.tab', el).forEach((x) => x.classList.toggle('on', x === b)); await drawTab(); },
    'export-menu': () => { const p = $('#exp-pop', el); p.hidden = !p.hidden; },
    transition: async (b) => {
      const a = b.dataset.a; const needs = b.dataset.c === '1';
      const texts = { submit: 'Send this version to expert review?', approve: 'Approve this version as verified expert knowledge? Your name is recorded as approver.',
        reject: 'Reject this version? It will never be used as training material.', request_revision: 'Send back for revision?',
        publish: 'Publish as the current training module? Any previous published version is preserved as superseded.' };
      const r = await confirmDialog(ACTION_LABEL[a][0], texts[a], ACTION_LABEL[a][0], true, needs);
      if (!r) return;
      try {
        const res = await api.post(`/api/versions/${v().id}/transition`, { action: a, comment: r.comment });
        toast(`Status → ${res.status}`); ctx.refreshNotifications();
      } catch (e) {
        if (e.details?.blockers) {
          await modal({ title: 'Cannot proceed yet', body: html`<ul class="blockers">${e.details.blockers.map((x) => html`<li>${x}</li>`)}</ul>`, actions: [{ label: 'OK' }] });
          return;
        }
        throw e;
      }
      await load(); tab = 'procedure'; draw();
    },
    revise: async () => {
      const r = await confirmDialog('Start a new revision', 'Creates an editable draft based on the current version. The published version stays live until the revision is approved and published.', 'Create revision', true);
      if (!r) return;
      await api.post(`/api/procedures/${data.procedure.id}/revisions`, { change_summary: r.comment });
      await load(); draw(); toast('Revision draft created');
    },
    confirm: async (b) => {
      await api.post(`/api/versions/${v().id}/confirm`, { item_ids: [b.dataset.id], confirmed: b.dataset.v === '1' });
      await load(v().id); draw();
    },
    'confirm-verified': async () => {
      const ids = content.steps.filter((s) => s.evidence_verified && s.source_type !== 'inference' && !s.safety_critical && !s.expert_confirmed).map((s) => s.step_id);
      if (!ids.length) return toast('No unconfirmed evidence-verified steps (inferred and safety-critical steps must be confirmed one by one)');
      await api.post(`/api/versions/${v().id}/confirm`, { item_ids: ids, confirmed: true });
      toast(`Confirmed ${ids.length} evidence-verified step(s). Inferred and safety-critical steps still need individual review.`);
      await load(v().id); draw();
    },
    'resolve-oq': async (b) => {
      const val = $(`#oq-${b.dataset.id}`, el).value.trim();
      if (!val) return toast('Type the expert\'s answer first', 'error');
      await api.post(`/api/versions/${v().id}/open-questions/${b.dataset.id}/resolve`, { resolution: val, add_as_tip: true });
      toast('Answer captured as an expert-authored tip'); await load(v().id); draw();
    },
    'dismiss-oq': async (b) => {
      await api.post(`/api/versions/${v().id}/open-questions/${b.dataset.id}/resolve`, { resolution: 'Not applicable — dismissed by expert', add_as_tip: false });
      await load(v().id); draw();
    },
    'edit-step': async (b) => {
      const s = content.steps.find((x) => x.step_id === b.dataset.id);
      const r = await stepModal(s); if (!r) return;
      Object.assign(s, r); await saveContent(`edited ${s.step_id}`);
    },
    'add-step': async () => {
      const r = await stepModal(null); if (!r) return;
      content.steps.push({ ...r, step_id: `step-x${Date.now().toString(36)}`, source_type: 'expert_edit', evidence_verified: true, confidence: 1, requires_expert_review: false, skills: content.skills.slice(0, 1) });
      await saveContent('added step');
    },
    'del-step': async (b) => {
      if (!(await confirmDialog('Delete step', 'Remove this step from the draft?', 'Delete'))) return;
      content.steps = content.steps.filter((x) => x.step_id !== b.dataset.id); await saveContent(`deleted ${b.dataset.id}`);
    },
    move: async (b) => {
      const i = content.steps.findIndex((x) => x.step_id === b.dataset.id); const j = i + +b.dataset.d;
      if (j < 0 || j >= content.steps.length) return;
      [content.steps[i], content.steps[j]] = [content.steps[j], content.steps[i]]; await saveContent('reordered steps');
    },
    'edit-q': async (b) => {
      const q = content.questions.find((x) => x.id === b.dataset.id) || { prompt: '', options: ['', '', ''], answer_index: 0, critical: false, explanation: '', step_id: null };
      const r = await modal({
        title: b.dataset.id ? 'Edit question' : 'Add question', wide: true,
        body: html`<label class="field"><span>Question</span><textarea id="q-p" rows="2">${q.prompt}</textarea></label>
          <label class="field"><span>Options (one per line)</span><textarea id="q-o" rows="4">${q.options.join('\n')}</textarea></label>
          <div class="grid g2"><label class="field"><span>Correct option number</span><input id="q-a" type="number" min="1" value="${q.answer_index + 1}"></label>
            <label class="field"><span>Linked step</span><select id="q-s"><option value="">—</option>${content.steps.map((s) => html`<option value="${s.step_id}" ${q.step_id === s.step_id ? 'selected' : ''}>${s.title}</option>`)}</select></label></div>
          <label class="field"><span>Explanation shown after answering</span><textarea id="q-e" rows="2">${q.explanation}</textarea></label>
          <label class="check"><input type="checkbox" id="q-c" ${q.critical ? 'checked' : ''}> Critical checkpoint item (failing it fails the assessment)</label>`,
        actions: [{ label: 'Cancel' }, { label: 'Save', onClick: (w) => ({ prompt: $('#q-p', w).value, options: $('#q-o', w).value.split('\n').map((s) => s.trim()).filter(Boolean),
          answer_index: +$('#q-a', w).value - 1, step_id: $('#q-s', w).value || null, explanation: $('#q-e', w).value, critical: $('#q-c', w).checked, origin: 'expert' }) }],
      });
      if (!r) return;
      if (b.dataset.id) Object.assign(q, r); else content.questions.push({ ...r, skill: content.skills[0] || null, weight: 1 });
      await saveContent('edited assessment'); tab = 'assessment'; draw();
    },
    'del-q': async (b) => { content.questions = content.questions.filter((x) => x.id !== b.dataset.id); await saveContent('removed question'); tab = 'assessment'; draw(); },
    'del-sc': async (b) => { content.scenarios = content.scenarios.filter((x) => x.id !== b.dataset.id); await saveContent('removed scenario'); tab = 'assessment'; draw(); },
    'goto-source': async (b) => {
      if (tab !== 'source') { tab = 'source'; await draw(); }
      const ts = b.dataset.ts;
      const line = $$('#tx [data-ts]', el).find((d) => d.dataset.ts && tsToSec(d.dataset.ts) <= tsToSec(ts) + 1 && tsToSec(d.dataset.ts) >= tsToSec(ts) - 1)
        || $$('#tx [data-ts]', el).filter((d) => d.dataset.ts && tsToSec(d.dataset.ts) <= tsToSec(ts)).pop();
      $$('#tx mark', el).forEach((m) => m.replaceWith(...m.childNodes));
      if (line) { line.innerHTML = `<mark>${esc(line.textContent)}</mark>`; line.scrollIntoView({ block: 'center', behavior: 'smooth' }); }
      const vid = $('#pvid', el); if (vid) { vid.currentTime = tsToSec(ts); vid.play().catch(() => {}); }
    },
    'view-ver': async (b) => { await load(b.dataset.id); tab = 'procedure'; draw(); },
    diff: async () => {
      const d = await api.get(`/api/procedures/${data.procedure.id}/diff?a=${$('#da', el).value}&b=${$('#db', el).value}`);
      mount($('#diff-out', el), html`<h4>v${d.a.version_no} → v${d.b.version_no}</h4>
        ${d.steps.filter((s) => s.change !== 'unchanged').map((s) => html`<div style="padding:6px 0;border-bottom:1px solid var(--line)">
          <span class="diff-${s.change === 'added' ? 'add' : s.change === 'removed' ? 'rem' : 'mod'}"><b>${s.change}</b></span> · ${s.title}
          ${s.fields ? Object.entries(s.fields).map(([k, f]) => html`<div class="diff-field"><span class="muted">${k}:</span> <del>${String(f.before ?? '')}</del> <ins>${String(f.after ?? '')}</ins></div>`) : ''}</div>`)}
        ${d.steps.every((s) => s.change === 'unchanged') ? html`<p class="muted small">No step changes.</p>` : ''}
        <p class="small muted" style="margin-top:8px">${Object.entries(d.counts).filter(([, c]) => c.before !== c.after).map(([k, c]) => `${k}: ${c.before}→${c.after}`).join(' · ') || 'Other sections unchanged.'}</p>`);
    },
    'save-tr': async () => {
      const steps = {};
      $$('[data-tr-step]', el).forEach((i) => { (steps[i.dataset.trStep] ||= {})[i.dataset.k] = i.value; });
      const safety = {}; $$('[data-tr-safety]', el).forEach((i) => { safety[i.dataset.trSafety] = i.value; });
      await api.put(`/api/versions/${v().id}/translations/ja`, { content: { title: $('[data-tr=title]', el).value, purpose: $('[data-tr=purpose]', el).value, steps, safety } });
      toast('Translation saved — awaiting review'); drawTab();
    },
    'review-tr': async () => { await api.post(`/api/versions/${v().id}/translations/ja/review`); toast('Translation approved'); drawTab(); },
    gap: async (b) => {
      await api.post(`/api/procedures/${data.procedure.id}/feedback`, { step_id: b.dataset.id, source: 'assessment', note: `Assessment analytics: learners repeatedly miss "${content.steps.find((s) => s.step_id === b.dataset.id)?.title}". Consider clarifying the instruction or adding a demonstration.` });
      toast('Improvement item logged'); await load(v().id); drawTab();
    },
    fb: async (b) => { await api.patch(`/api/feedback/${b.dataset.id}`, { status: b.dataset.s }); await load(v().id); drawTab(); },
    flag: async (b) => {
      const r = await confirmDialog('Flag this step as unclear', 'Your note goes to the expert as input for the next revision.', 'Send', true, true);
      if (!r) return;
      await api.post(`/api/procedures/${data.procedure.id}/feedback`, { step_id: b.dataset.id, note: r.comment });
      toast('Thanks — sent to the expert');
    },
    ask: () => openAssistant(data.procedure.id),
  });
  return off;
}
